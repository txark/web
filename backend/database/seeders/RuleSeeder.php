 *
 * ตัดเศษข้อความที่ขาดจากการคัดลอก และเขียน WVDL ให้เป็นรูปเดียวกัน
 * ไม่ทับข้อมูลเดิม: ทำทีละหมวด ถ้าหมวดนั้นมีกฎอยู่แล้วจะข้าม (ประธาน/แอดมินแก้ในระบบได้ภายหลัง)
