    private const SHOW_TITLE = ['MAX-004', 'MAX-005', 'เงื่อนไขเพิ่มเติม'];

    /** @return array<string, list<array<string, string>>> */
    public static function all(): array
    {
        // ทุกหมวดแสดงแบบเดียวกัน: ข้อหลักแต่ละข้อเป็นการ์ดข้อกฎ มีชื่อเรื่องเด่น (ไม่มีรหัส) และเนื้อหาเป็นย่อหน้า/หัวข้อย่อย
        // ยกเว้นหมวดค่าบริการที่เป็นรายการราคา
        $out = [];
        foreach (self::raw() as $key => $items) {
            $out[$key] = $key === 'fees' ? $items : self::titled($items);
        }

        return $out;
    }

    /**
     * ข้อหลักแต่ละข้อ (CC-001, DUTY-001 ฯลฯ) เป็น "ข้อกฎ" ที่มีเลขกำกับในหมวดเดียวกัน ไม่ใช่หมวดย่อย:
     * หัวข้อ (รหัส — ชื่อ) ถูกรวมเข้าหน้าข้อกฎแรกของข้อนั้น ยกเว้นข้อที่เป็นตารางราคา (CC-004) ที่คงหัวข้อไว้
     *
     * @param  list<array<string, string>>  $items
     * @return list<array<string, string>>
     */
    private static function flatten(array $items): array
    {
        $out = [];
        $pending = null;
        foreach ($items as $item) {
            if (($item['kind'] ?? 'rule') === 'heading') {
                $pending = $item;

                continue;
            }
            if ($pending !== null) {
                if (($item['kind'] ?? 'rule') === 'price') {
                    $out[] = $pending;
                } elseif (($item['kind'] ?? 'rule') === 'rule') {
                    $item['body'] = $pending['title'].': '.$item['body'];
                }
                $pending = null;
            }
            $out[] = $item;
        }

        return $out;
    }

    /**
     * หัวข้อ (รหัส — ชื่อ) กลายเป็นชื่อเรื่องเด่น (ไม่ใส่รหัส) ของการ์ดข้อกฎ และข้อกฎทั้งหมดใต้หัวข้อรวมเป็นการ์ดเดียว
     *  - ข้อเดียว: คงเนื้อหาและบทลงโทษไว้ตามเดิม
     *  - หลายข้อ: ข้อแรกเป็นย่อหน้านำถ้าลงท้ายด้วย "ดังนี้/ต่อไปนี้/ระดับ" ที่เหลือเป็นหัวข้อย่อย (•)
     *    ถ้ามีบทลงโทษข้อเดียวคงไว้ในช่องโทษ ถ้ามีหลายข้อพับเข้าไปในข้อความของหัวข้อย่อยนั้น
     *  - ข้อความ/กล่องเน้น/รายการราคาใต้หัวข้อ แสดงต่อท้ายการ์ด
     *
     * @param  list<array<string, string>>  $items
     * @return list<array<string, string>>
     */
    private static function titled(array $items): array
    {
        $out = [];
        $flush = function (?string $title, ?string $code, array $rules, array $extras) use (&$out) {
            if ($rules) {
                $card = ['kind' => 'rule'];
                // ไม่แสดงชื่อเรื่องของข้อ ยกเว้นข้อที่เลือกไว้ใน SHOW_TITLE
                if (in_array($code, self::SHOW_TITLE, true) || in_array($title, self::SHOW_TITLE, true)) {
                    $card['title'] = $title;
                }
                if (count($rules) === 1) {
                    $card['body'] = $rules[0]['body'];
                    if (! empty($rules[0]['penalty'])) {
                        $card['penalty'] = $rules[0]['penalty'];
                    }
                } else {
                    $intro = preg_match('/(ดังนี้|ต่อไปนี้|ระดับ)$/u', $rules[0]['body']) === 1 ? array_shift($rules) : null;
                    $withPenalty = count(array_filter($rules, fn ($r) => ! empty($r['penalty'])));
                    $lines = array_map(fn ($r) => '• '.$r['body'].($withPenalty > 1 && ! empty($r['penalty']) ? ': '.$r['penalty'] : ''), $rules);
                    $card['body'] = implode("
", array_filter([$intro['body'] ?? null, ...$lines]));
                    if ($withPenalty === 1) {
                        $card['penalty'] = array_values(array_filter(array_column($rules, 'penalty')))[0];
                    }
                }
                $out[] = $card;
            }
            array_push($out, ...$extras);
        };

        $title = null;
        $code = null;
        $rules = [];
        $extras = [];
        foreach ($items as $item) {
            $kind = $item['kind'] ?? 'rule';
            if ($kind === 'heading') {
                $flush($title, $code, $rules, $extras);
                if (! empty($item['sub'])) {
                    // หมวดย่อยจริง (แสดงเป็นแถบหัวข้อในหน้ากฎและสารบัญ) เช่น REG แยกแก๊ง / ครอบครัว
                    $out[] = ['kind' => 'heading', 'title' => $item['title']];
                    $title = null;
                    $rules = [];
                    $extras = [];

                    continue;
                }
                $code = preg_match('/^([A-Z]+-\d{3}) — /u', $item['title'], $m) ? $m[1] : null;
                $title = preg_replace('/^[A-Z]+-\d{3} — /u', '', $item['title']);
                $rules = [];
                $extras = [];
            } elseif ($kind === 'rule') {
                $rules[] = $item;
            } else {
                $extras[] = $item;
            }
        }
        $flush($title, $code, $rules, $extras);

        return $out;
    }

